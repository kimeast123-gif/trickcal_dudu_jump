"""World 5 「용족동굴」 assets from the user's package (DUDU_WORLD5_DRAGON_CAVE_MASTER_STAGE51_*).

    python tools/dragon_cave_assets.py <unpacked package folder> [<unpacked 5-2 package>]

- 01_WORLD5_BACKGROUNDS/WORLD5_ROOM_0N_*.png -> assets/world/dragoncave/bgN.webp (the five rooms, unchanged pixels)
- 03_STAGE_5-1_ART_CANDIDATE/JADE_PLATFORM_CANDIDATE/sprites/png/JADE_*.png -> assets/terrain/dragon_cave/<part>.webp,
  cropped to their visible pixels, plus parts.js: window.DC_PARTS = {part: [width, height, walking surface row]}.
  The walking surface row is the first row whose middle 60% is at least 90% opaque (the flat top edge the feet stand on).
- 5-2 package (DUDU_WORLD5_STAGE52_RUDE_PINBALL_MOTION_REV2_*): references/02_RUDE_CAVE_GYM_BG.png -> gym.webp and
  references/03_PINBALL_GYM_BG.png -> pinball.webp in assets/world/dragoncave/
The platform pieces are the package's TEST CANDIDATE art (not approved); this script does not repaint or stretch them.
"""
import glob, json, os, sys
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
PARTS = ['long_left', 'long_mid', 'long_right', 'float_small', 'float_medium', 'float_large', 'float_compact',
         'checkpoint_pad', 'bookshelf_ledge']


def surface_row(im):
    a = im.getchannel('A')
    w, h = im.size
    x0, x1 = int(w * 0.2), int(w * 0.8)
    for y in range(h):
        row = [a.getpixel((x, y)) for x in range(x0, x1)]
        if sum(1 for v in row if v >= 230) >= 0.9 * len(row):
            return y
    return 0


def main(src, src52=None):
    bg_out = os.path.join(ROOT, 'assets', 'world', 'dragoncave')
    pt_out = os.path.join(ROOT, 'assets', 'terrain', 'dragon_cave')
    os.makedirs(bg_out, exist_ok=True)
    os.makedirs(pt_out, exist_ok=True)
    for f in sorted(glob.glob(os.path.join(src, '01_WORLD5_BACKGROUNDS', 'WORLD5_ROOM_0*.png'))):
        n = os.path.basename(f)[len('WORLD5_ROOM_0'):][0]
        Image.open(f).convert('RGB').save(os.path.join(bg_out, f'bg{n}.webp'), 'WEBP', quality=90, method=6)
        print('background', n, os.path.basename(f))
    table = {}
    sprite_dir = os.path.join(src, '03_STAGE_5-1_ART_CANDIDATE', 'JADE_PLATFORM_CANDIDATE', 'sprites', 'png')
    for part in PARTS:
        im = Image.open(os.path.join(sprite_dir, f'JADE_{part}.png')).convert('RGBA')
        box = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        im = im.crop(box)
        surf = surface_row(im)
        im.save(os.path.join(pt_out, f'{part}.webp'), 'WEBP', lossless=True, method=6)
        table[part] = [im.width, im.height, surf]
        print(part, table[part])
    with open(os.path.join(pt_out, 'parts.js'), 'w', encoding='utf8', newline='\n') as fh:
        fh.write('// generated by tools/dragon_cave_assets.py: [width, height, walking surface row]\n')
        fh.write('window.DC_PARTS = ' + json.dumps(table, separators=(',', ':')) + ';\n')
    if src52:
        for name, out in (('02_RUDE_CAVE_GYM_BG.png', 'gym'), ('03_PINBALL_GYM_BG.png', 'pinball')):
            Image.open(os.path.join(src52, 'references', name)).convert('RGB').save(os.path.join(bg_out, out + '.webp'), 'WEBP', quality=90, method=6)
            print('background', out, name)


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
