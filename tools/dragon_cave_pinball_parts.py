"""World 5 / 5-2 pinball parts from the user's asset board (transparent background, 1448 x 1086).

    python tools/dragon_cave_pinball_parts.py <board image>

Copies the board to docs/world5/source/pinball_parts_board.webp and writes
  assets/world/dragoncave/pinball/<part>.webp   each part cropped from the board (boxes below, measured on the board)
  assets/world/dragoncave/pinball/parts.js      window.PB_PARTS = {part: [width, height]}
The score panel ("TOTAL 0kg") and the score badge ("+5kg") carry sample numbers: the number's box is painted over row
by row with the colours just beside it, so the game can write the real kg there. "TOTAL" and the panel frame stay.
"""
import json, os, shutil, sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOXES = {
    'flipper_l': (58, 37, 447, 185), 'flipper_r': (511, 37, 899, 185),
    'plunger': (971, 22, 1187, 194),
    'arc_l': (18, 217, 179, 468), 'arc_r': (220, 217, 377, 468),
    'rail_long': (398, 248, 897, 329), 'rail_short': (460, 375, 808, 443), 'rail_vert': (916, 214, 982, 462),
    'panel': (1014, 213, 1432, 451),
    'plate20': (44, 480, 307, 752), 'plate10': (343, 522, 557, 744), 'plate3': (585, 565, 746, 739),
    'sandbag': (793, 460, 932, 763),
    'flag': (21, 898, 175, 1075),
    'arrows': (739, 965, 900, 1051),
    'light_red': (1019, 961, 1108, 1054), 'light_green': (1116, 963, 1202, 1054),
    'badge': (1224, 954, 1431, 1055),
    'floor': (364, 998, 724, 1056),
}
# box inside the part that holds the sample number: every row of it is repainted with a blend between the colours
# just left and right of the box on that row (the number, its outline and its glow all go)
ERASE = {'panel': (60, 110, 360, 196, 10), 'badge': (44, 16, 162, 86, 6)}


def erase_number(im, x0, y0, x1, y1, edge):
    a = np.array(im).astype(np.float64)
    for y in range(y0, y1):
        left = np.median(a[y, x0 - edge:x0, :3], axis=0)
        right = np.median(a[y, x1:x1 + edge, :3], axis=0)
        u = np.linspace(0, 1, x1 - x0)[:, None]
        a[y, x0:x1, :3] = left * (1 - u) + right * u
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), 'RGBA')


def main(src):
    board = Image.open(src).convert('RGBA')
    os.makedirs(os.path.join(ROOT, 'docs', 'world5', 'source'), exist_ok=True)
    board.save(os.path.join(ROOT, 'docs', 'world5', 'source', 'pinball_parts_board.webp'), 'WEBP', lossless=True)
    out = os.path.join(ROOT, 'assets', 'world', 'dragoncave', 'pinball')
    os.makedirs(out, exist_ok=True)
    table = {}
    for name, box in BOXES.items():
        im = board.crop(box)
        if name in ERASE:
            im = erase_number(im, *ERASE[name])
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        im = im.crop(bb)
        im.save(os.path.join(out, name + '.webp'), 'WEBP', quality=92, method=6)
        table[name] = [im.width, im.height]
        print(f'{name:12s} {im.size}')
    with open(os.path.join(out, 'parts.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// generated by tools/dragon_cave_pinball_parts.py: [width, height]\n')
        fh.write('window.PB_PARTS = ' + json.dumps(table, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1])
