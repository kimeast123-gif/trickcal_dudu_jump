"""World 5 / 5-3 「키디언의 어두운 미로」 art from the user's package (DUDU_WORLD5_STAGE53_KIDIAN_CLAUDE_MASTER_REV2_*).

    python tools/dragon_cave_kidian_parts.py <unpacked 5-3 package>

- 01_SOURCE_LAYOUT_BG/STAGE53_USER_OFFICIAL_BACKGROUND.png -> assets/world/dragoncave/kidian_bg.webp (unchanged)
- 04_ART_CANDIDATE/KIDIAN_DARK_MAZE_ATLAS_CANDIDATE.png -> assets/world/dragoncave/kidian/<part>.webp + parts.js
  (window.KD_PARTS = {part: [width, height, walking surface row]}), boxes measured on the sheet.
- 03_AUDIO/19. Dragon Cave (Abyss).mp3 -> assets/event/dragon_abyss.mp3

Checked on the candidate sheet (the package asks for it before use): the parts' visible pixels are solid (median alpha
252 of 255; the "mostly semi-transparent" figure in the package counts only alpha 255 as opaque). What is wrong is a
faint halo: about 114,000 pixels around the parts with alpha under 40, many of them red, which shows as a thin red
line along some top edges on a dark background. Those halo pixels are cleared (alpha < 40 -> 0); nothing else is
changed, no alpha is raised. The walking surface row is the first row whose middle 60% is at least 90% opaque.
"""
import json, os, shutil, sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOXES = {
    # plain stone ledges: left end, middle, right end, small, wide float
    'plain_l': (37, 64, 250, 175), 'plain_m': (279, 64, 642, 166), 'plain_r': (672, 64, 888, 168),
    'plain_s': (940, 93, 1099, 141), 'plain_f': (1131, 69, 1417, 168),
    # sand-topped ledges (the sketch's brown-bottomed ones)
    'sand_l': (35, 203, 250, 328), 'sand_m': (280, 208, 647, 318), 'sand_r': (676, 205, 888, 324),
    'sand_s': (936, 236, 1097, 291), 'sand_f': (1131, 213, 1417, 320),
    # obsidian
    'shard1': (93, 504, 140, 581), 'shard2': (218, 484, 314, 581), 'shard3': (390, 472, 509, 583),
    # rock walls and blocks
    'block': (92, 698, 196, 800), 'wall_s': (274, 659, 385, 817), 'pillar': (480, 614, 576, 822),
    'cliff': (699, 603, 892, 822),
    # start and goal pads (with their flags)
    'pad_start': (261, 852, 535, 1057), 'pad_goal': (642, 828, 1148, 1060),
}


def surface_row(im):
    a = np.array(im)[:, :, 3]
    h, w = a.shape
    x0, x1 = int(w * 0.2), int(w * 0.8)
    for y in range(h):
        if (a[y, x0:x1] >= 230).mean() >= 0.9:
            return y
    return 0


def main(pkg):
    shutil.copyfile(os.path.join(pkg, '03_AUDIO', '19. Dragon Cave (Abyss).mp3'), os.path.join(ROOT, 'assets', 'event', 'dragon_abyss.mp3'))
    bg = Image.open(os.path.join(pkg, '01_SOURCE_LAYOUT_BG', 'STAGE53_USER_OFFICIAL_BACKGROUND.png')).convert('RGB')
    bg.save(os.path.join(ROOT, 'assets', 'world', 'dragoncave', 'kidian_bg.webp'), 'WEBP', quality=90, method=6)
    sheet = np.array(Image.open(os.path.join(pkg, '04_ART_CANDIDATE', 'KIDIAN_DARK_MAZE_ATLAS_CANDIDATE.png')).convert('RGBA'))
    halo = sheet[:, :, 3] < 40
    print('halo pixels cleared', int((halo & (sheet[:, :, 3] > 0)).sum()))
    sheet[halo] = 0
    sheet = Image.fromarray(sheet, 'RGBA')
    out = os.path.join(ROOT, 'assets', 'world', 'dragoncave', 'kidian')
    os.makedirs(out, exist_ok=True)
    table = {}
    for name, box in BOXES.items():
        im = sheet.crop(box)
        im = im.crop(im.getchannel('A').getbbox())
        im.save(os.path.join(out, name + '.webp'), 'WEBP', quality=92, method=6)
        table[name] = [im.width, im.height, surface_row(im)]
        print(f'{name:10s} {table[name]}')
    with open(os.path.join(out, 'parts.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// generated by tools/dragon_cave_kidian_parts.py: [width, height, walking surface row]\n')
        fh.write('window.KD_PARTS = ' + json.dumps(table, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1])
